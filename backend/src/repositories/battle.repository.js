'use strict';

const db = require('../config/database');
const { query } = db;

/**
 * All SQL for the `battles` table lives here. Services never write raw
 * queries; controllers never touch this repository directly. See
 * Backend Implementation Guide v1.0 for the layering rules, and
 * migrations 004_battles.sql / 013_battle_sessions.sql for the schema
 * this repository reads and writes.
 */

/**
 * Finds any battle for a player (as attacker or defender) that is still
 * `in_progress`. Used to reject duplicate challenges and to resolve the
 * player's current session on reconnect.
 */
async function findActiveBattleForPlayer(playerId, executor = db) {
  const result = await executor.query(
    `SELECT * FROM battles
     WHERE (attacker_id = $1 OR defender_id = $1)
       AND status = 'in_progress'
     ORDER BY started_at DESC
     LIMIT 1`,
    [playerId]
  );
  return result.rows[0] || null;
}

/**
 * Creates a new battle row in 'in_progress' status. `battleId` and
 * `photonRoomName` are both generated by the caller (battle.service.js)
 * BEFORE this insert — battleId first, then photonRoomName derived from
 * it as `battle_{battle_id}` — per the approved Photon Fusion room
 * lifecycle (Photon & Mapbox Integration v1.0 section 1.2, step 2: "the
 * server requests a new Photon session named battle_{battle_id}") and
 * Unity MVP Implementation Plan v1.0's Phase 5 note ("Session تُنشأ باسم
 * battle_{battle_id}"). The battle_id is therefore inserted explicitly
 * rather than left to the column's gen_random_uuid() default, so the
 * room name and the row's primary key are always derived from the same
 * value.
 */
async function createBattle({
  battleId,
  attackerId,
  defenderId,
  photonRoomName,
  locationLat,
  locationLng,
  sessionExpiresAt,
  hostPlayerId,
  hostAuthoritySecret,
  matchNonce,
  rulesVersion,
}, executor = db) {
  const result = await executor.query(
    `INSERT INTO battles
       (battle_id, attacker_id, defender_id, status, photon_room_name,
        location_lat, location_lng, session_started_at, session_expires_at,
        host_player_id, host_authority_secret, match_nonce, rules_version)
     VALUES ($1, $2, $3, 'in_progress', $4, $5, $6, now(), $7, $8, $9, $10, $11)
     RETURNING *`,
    [
      battleId,
      attackerId,
      defenderId,
      photonRoomName,
      locationLat,
      locationLng,
      sessionExpiresAt,
      hostPlayerId,
      hostAuthoritySecret,
      matchNonce,
      rulesVersion,
    ]
  );
  return result.rows[0];
}

async function getById(battleId) {
  const result = await query('SELECT * FROM battles WHERE battle_id = $1', [battleId]);
  return result.rows[0] || null;
}

async function getByPhotonRoomName(photonRoomName) {
  const result = await query('SELECT * FROM battles WHERE photon_room_name = $1', [photonRoomName]);
  return result.rows[0] || null;
}

/**
 * Marks one side (attacker or defender) as ready. `side` must be
 * 'attacker' or 'defender' — validated by the caller (service layer),
 * never interpolated directly, to avoid building dynamic SQL from
 * unvalidated input.
 */
async function setPlayerReady(battleId, side) {
  const column = side === 'attacker' ? 'attacker_ready' : 'defender_ready';
  const result = await query(
    `UPDATE battles SET ${column} = true WHERE battle_id = $1 RETURNING *`,
    [battleId]
  );
  return result.rows[0] || null;
}

/**
 * Records a disconnect timestamp and reconnect deadline for one side.
 * Sprint 5 scope: session state only — no forfeit/result decision here,
 * that is decided by the service layer once the deadline has passed.
 */
async function recordDisconnect(battleId, side, disconnectedAt, reconnectDeadline) {
  const disconnectedCol = side === 'attacker' ? 'attacker_disconnected_at' : 'defender_disconnected_at';
  const deadlineCol = side === 'attacker' ? 'attacker_reconnect_deadline' : 'defender_reconnect_deadline';
  const result = await query(
    `UPDATE battles
     SET ${disconnectedCol} = $2, ${deadlineCol} = $3
     WHERE battle_id = $1
     RETURNING *`,
    [battleId, disconnectedAt, reconnectDeadline]
  );
  return result.rows[0] || null;
}

/**
 * Clears disconnect tracking for one side on successful reconnect.
 */
async function clearDisconnect(battleId, side) {
  const disconnectedCol = side === 'attacker' ? 'attacker_disconnected_at' : 'defender_disconnected_at';
  const deadlineCol = side === 'attacker' ? 'attacker_reconnect_deadline' : 'defender_reconnect_deadline';
  const result = await query(
    `UPDATE battles
     SET ${disconnectedCol} = NULL, ${deadlineCol} = NULL
     WHERE battle_id = $1
     RETURNING *`,
    [battleId]
  );
  return result.rows[0] || null;
}

/**
 * Marks the battle as forfeited by the given player (the one who failed
 * to reconnect within the grace period). Sets status only — NOT
 * winner_id/loser_id, which belongs to final battle result logic
 * (Sprint 6, per Battle System v1.0 section 2's resolve step).
 */
async function markForfeited(battleId, forfeitedByPlayerId) {
  const result = await query(
    `UPDATE battles
     SET status = 'forfeited', forfeited_by = $2, ended_at = now()
     WHERE battle_id = $1 AND status = 'in_progress'
     RETURNING *`,
    [battleId, forfeitedByPlayerId]
  );
  return result.rows[0] || null;
}

async function cancelBattle(battleId) {
  const result = await query(
    `UPDATE battles
     SET status = 'cancelled', ended_at = now()
     WHERE battle_id = $1 AND status = 'in_progress'
     RETURNING *`,
    [battleId]
  );
  return result.rows[0] || null;
}

/**
 * Persists the final result of a battle. `winner_id`/`loser_id` and
 * `duration_seconds` are columns that already existed on this table
 * since 004_battles.sql. Both nullable columns are left NULL for a Draw
 * (GDD's Overtime rule can end a match with no winner) — `status =
 * 'resolved'` plus `winner_id IS NULL` is how a resolved Draw is
 * distinguished from a still-in-progress battle, without a schema
 * change. Restricted to 'in_progress' rows so a battle can only ever be
 * resolved once (idempotency / no double-resolve — see
 * battle.service.js resolveBattle for the SESSION_EXPIRED check on the
 * read side of this same guarantee).
 *
 * `eventSeq` also updates `last_event_seq` in the same statement — this
 * is the final write for the battle, so recording the host's last-seen
 * combat-event counter here (rather than a separate UPDATE) keeps the
 * duplicate/replay guard's bookkeeping inside the same atomic step as
 * the result itself (Sprint 6 final security correction).
 *
 * `status` defaults to 'resolved' but accepts 'pending_review' (Sprint 6
 * final gameplay-completion pass — Alpha security mode,
 * 015_battle_pending_review.sql): a signed result that trips a
 * plausibility heuristic is still recorded — winner_id/loser_id/
 * duration_seconds/last_event_seq are still written so the claim is
 * captured for review and can never be resubmitted/replayed — but the
 * row is left in 'pending_review' rather than 'resolved', which
 * battle.service.js resolveBattle uses as the signal to skip the
 * Influence/Control/log writes entirely.
 *
 * `executor` defaults to the shared pool but accepts a transaction
 * client (config/database.js's withTransaction) — resolveBattle runs
 * this UPDATE in the same transaction as the Influence/Control/log
 * writes so a battle is never left "resolved" with those side effects
 * only partially applied.
 */
/**
 * Ends the in_progress battles that can no longer finish normally (see
 * utils/battleLifecycle.js for the rules): an expired reconnect deadline
 * -> 'forfeited' (the existing forfeit rule); not both ready within the
 * ready timeout, or past the no-result cutoff -> 'cancelled'. Scoped to
 * one battle (`battleId`) or to every battle of `playerIds`.
 *
 * One guarded UPDATE (`status = 'in_progress'`), so it is idempotent and
 * safe under concurrency: PostgreSQL row locks mean simultaneous calls,
 * and a simultaneous resolveBattle / markForfeited, produce exactly one
 * terminal outcome — whoever commits second matches no row. A battle
 * that already ended (resolved, forfeited, cancelled, pending_review) is
 * never touched, and nothing is deleted. Returns the rows it ended.
 */
async function expireStaleBattles({ battleId = null, playerIds = null }, limits, executor = db) {
  if (!battleId && !(playerIds && playerIds.length)) {
    throw new Error('expireStaleBattles needs a battleId or playerIds');
  }
  const attackerGone = 'attacker_disconnected_at IS NOT NULL AND attacker_reconnect_deadline < now()';
  const defenderGone = 'defender_disconnected_at IS NOT NULL AND defender_reconnect_deadline < now()';
  const startedAt = 'COALESCE(session_started_at, started_at)';
  const result = await executor.query(
    `UPDATE battles
     SET status = CASE WHEN (${attackerGone}) OR (${defenderGone}) THEN 'forfeited' ELSE 'cancelled' END,
         forfeited_by = CASE WHEN (${attackerGone}) THEN attacker_id
                             WHEN (${defenderGone}) THEN defender_id
                             ELSE forfeited_by END,
         ended_at = now()
     WHERE status = 'in_progress'
       AND (battle_id = $1 OR attacker_id = ANY($2::uuid[]) OR defender_id = ANY($2::uuid[]))
       AND ((${attackerGone})
            OR (${defenderGone})
            OR (NOT (attacker_ready AND defender_ready) AND ${startedAt} + $3 * interval '1 second' < now())
            OR ${startedAt} + $4 * interval '1 second' < now())
     RETURNING *`,
    [battleId, playerIds || [], limits.readyTimeoutSeconds, limits.noResultCutoffSeconds]
  );
  return result.rows;
}

async function resolveBattle(battleId, { winnerId, loserId, durationSeconds, eventSeq, status = 'resolved' }, executor = db) {
  const result = await executor.query(
    `UPDATE battles
     SET status = $6, winner_id = $2, loser_id = $3,
         duration_seconds = $4, last_event_seq = $5, ended_at = now()
     WHERE battle_id = $1 AND status = 'in_progress'
     RETURNING *`,
    [battleId, winnerId, loserId, durationSeconds, eventSeq, status]
  );
  return result.rows[0] || null;
}

/**
 * Serializes challenge creation for these players until the surrounding
 * transaction ends (transaction-scoped advisory locks, taken in a fixed
 * order so two challenges between the same pair cannot deadlock). Without
 * it, two simultaneous challenges — a double tap, or two players
 * challenging each other — both pass the active-battle check and create
 * two battles.
 */
async function lockPlayersForChallenge(playerIds, executor) {
  for (const playerId of [...playerIds].sort()) {
    await executor.query('SELECT pg_advisory_xact_lock(hashtextextended($1, 0))', [`battle-challenge:${playerId}`]);
  }
}

